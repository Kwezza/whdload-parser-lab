/* Minimal test harness                                                   */

static int g_pass = 0;
static int g_fail = 0;

#define CHECK(cond, msg) \
    do { \
        if (cond) { \
            printf("  PASS: %s\n", msg); \
            g_pass++; \
        } else { \
            printf("  FAIL: %s\n", msg); \
            g_fail++; \
        } \
    } while (0)

static void print_sep(const char *name)
{
    printf("\n--- %s ---\n", name);
}

/*------------------------------------------------------------------------*/
/* T12 fixture: comparison helper                                         */

static int results_match_expected(
    const WhdTlvStringList *r,
    const char * const     *expected,
    unsigned int            expected_count)
{
    unsigned int i;

    if (r == NULL || expected == NULL) {
        return 0;
    }
    if (r->count != expected_count) {
        return 0;
    }
    for (i = 0u; i < expected_count; ++i) {
        if (r->items == NULL || r->items[i] == NULL || expected[i] == NULL) {
            return 0;
        }
        if (strcmp(r->items[i], expected[i]) != 0) {
            return 0;
        }
    }
    return 1;
}

