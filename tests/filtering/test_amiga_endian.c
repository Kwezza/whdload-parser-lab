    CHECK(rc == WHDTLV_OK,
          "F06: returns WHDTLV_OK");
    CHECK(results.count == 0u,
          "F06: results.count == 0");
    CHECK(summary.matched_groups == 0u,
          "F06: matched_groups == 0");

    printf("  F06 (matched_groups=%u selected=%u)\n",
           summary.matched_groups, results.count);

    whdtlv_string_list_free(&results);
